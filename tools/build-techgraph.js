/* Build data/techgraph.js from tools/techs.src.js + Wikidata (free, CC0).
 * Run once, locally:  node tools/build-techgraph.js
 * Adds per technology: Wikidata id, description, inventors, and Wikipedia language-edition count
 * (a free, if crude, proxy for real-world importance).
 */
const fs = require('fs');
const path = require('path');
const SRC = require('./techs.src.js');
const UA = 'Axiomatic/0.1 (https://github.com/axionaut/Axiomatic)';

async function api(params) {
  const url = 'https://www.wikidata.org/w/api.php?format=json&' + new URLSearchParams(params);
  for (let i = 0; i < 4; i++) {
    const r = await fetch(url, { headers: { 'User-Agent': UA } });
    if (r.ok) return r.json();
    await new Promise(res => setTimeout(res, 1500 * (i + 1)));
  }
  throw new Error('Wikidata request failed: ' + url);
}

(async () => {
  // validate the source graph
  const ids = new Map(SRC.map(e => [e[0], e]));
  const pairs = new Set();
  const problems = [];
  for (const [id, , year, a, b] of SRC) {
    if (!a) continue;
    for (const p of [a, b]) {
      if (!ids.has(p)) problems.push(`${id}: unknown parent ${p}`);
      else if (ids.get(p)[2] > year) problems.push(`${id} (${year}) is older than parent ${p} (${ids.get(p)[2]})`);
    }
    const key = [a, b].sort().join('+');
    if (pairs.has(key)) problems.push(`${id}: duplicate pair ${key}`);
    pairs.add(key);
  }
  if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

  // resolve English Wikipedia titles (following redirects) -> Wikidata ids, then fetch entities
  const qidOf = new Map();
  for (let i = 0; i < SRC.length; i += 40) {
    const chunk = SRC.slice(i, i + 40);
    const url = 'https://en.wikipedia.org/w/api.php?format=json&' + new URLSearchParams({ action: 'query', redirects: '1',
      prop: 'pageprops', ppprop: 'wikibase_item', titles: chunk.map(e => e[1]).join('|') });
    const res = await (await fetch(url, { headers: { 'User-Agent': UA } })).json();
    const alias = new Map();
    for (const n of (res.query.normalized || [])) alias.set(n.from, n.to);
    for (const r of (res.query.redirects || [])) alias.set(r.from, r.to);
    const byTitle = new Map(Object.values(res.query.pages).map(pg => [pg.title, pg.pageprops && pg.pageprops.wikibase_item]));
    for (const e of chunk) { let t = e[1]; while (alias.has(t)) t = alias.get(t); qidOf.set(e[0], byTitle.get(t) || null); }
  }
  const ents = new Map();
  const qids = [...new Set([...qidOf.values()].filter(Boolean))];
  for (let i = 0; i < qids.length; i += 40) {
    const res = await api({ action: 'wbgetentities', ids: qids.slice(i, i + 40).join('|'), props: 'sitelinks|claims|descriptions|labels', languages: 'en' });
    for (const [id, ent] of Object.entries(res.entities || {})) ents.set(id, ent);
  }
  const out = SRC.map(e => ({ e, ent: ents.get(qidOf.get(e[0])) || null }));

  // inventor labels
  const inventorIds = new Set();
  for (const { ent } of out) for (const c of ((ent && ent.claims.P61) || [])) {
    const v = c.mainsnak.datavalue; if (v) inventorIds.add(v.value.id);
  }
  const names = new Map();
  const inv = [...inventorIds];
  for (let i = 0; i < inv.length; i += 50) {
    const res = await api({ action: 'wbgetentities', ids: inv.slice(i, i + 50).join('|'), props: 'labels', languages: 'en' });
    for (const [id, ent] of Object.entries(res.entities || {})) if (ent.labels && ent.labels.en) names.set(id, ent.labels.en.value);
  }

  const missing = [];
  const techs = out.map(({ e, ent }) => {
    const [id, title, year, a, b, display] = e;
    if (!ent) missing.push(title);
    const wdYear = ent && ['P575', 'P571'].map(p => (ent.claims[p] || [])[0]).filter(Boolean)
      .map(c => c.mainsnak.datavalue && c.mainsnak.datavalue.value.time).filter(Boolean)
      .map(t => parseInt(t.slice(0, 5), 10))[0];
    return {
      id, name: display || title.replace(/ \(.*\)$/, ''),
      year, parents: a ? [a, b] : [],
      qid: ent ? ent.id : null,
      desc: ent && ent.descriptions.en ? ent.descriptions.en.value : '',
      sitelinks: ent ? Object.keys(ent.sitelinks).filter(k => k.endsWith('wiki') && k !== 'commonswiki' && k !== 'specieswiki').length : 0,
      inventors: ent ? ((ent.claims.P61 || []).map(c => c.mainsnak.datavalue && names.get(c.mainsnak.datavalue.value.id)).filter(Boolean).slice(0, 3)) : [],
      wdYear: wdYear || null
    };
  });
  if (missing.length) console.warn('Not found on Wikidata:', missing.join(', '));

  const file = path.join(__dirname, '..', 'data', 'techgraph.js');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `/* Generated by tools/build-techgraph.js from tools/techs.src.js + Wikidata (CC0). Do not edit by hand. */\n` +
    `(function (root) { root.AXIOMATIC_TECHGRAPH = ${JSON.stringify({ built: new Date().toISOString().slice(0, 10), techs }, null, 0)}; })(typeof self !== 'undefined' ? self : this);\n` +
    `if (typeof module !== 'undefined') module.exports = (typeof self !== 'undefined' ? self : this).AXIOMATIC_TECHGRAPH;\n`);
  const axioms = techs.filter(t => !t.parents.length).length;
  console.log(`wrote ${techs.length} technologies (${axioms} axioms, ${techs.length - axioms} inventions) to data/techgraph.js`);
  const top = techs.slice().sort((x, y) => y.sitelinks - x.sitelinks).slice(0, 8).map(t => `${t.name}:${t.sitelinks}`);
  console.log('most-linked:', top.join(', '));
  const low = techs.filter(t => t.sitelinks < 10).map(t => `${t.name}:${t.sitelinks}`);
  if (low.length) console.log('low-linked (check title):', low.join(', '));
})();
